-- 4. Helper function to award streak badge to alumni profile
CREATE OR REPLACE FUNCTION public.award_streak_badge(
  p_user_id BIGINT,
  p_badge TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  -- Add badge to alumni_profiles if not already present
  UPDATE public.alumni_profiles
  SET badges = array_append(badges, p_badge)
  WHERE id = p_user_id
    AND NOT (p_badge = ANY(coalesce(badges, '{}'::text[])));

  -- Add to user_streaks milestone_badges
  UPDATE public.user_streaks
  SET milestone_badges = array_append(milestone_badges, p_badge),
      updated_at = now()
  WHERE user_id = p_user_id
    AND NOT (p_badge = ANY(coalesce(milestone_badges, '{}'::text[])));
END;
$$;
