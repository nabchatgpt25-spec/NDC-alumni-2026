-- 1. user_streaks table
CREATE TABLE IF NOT EXISTS public.user_streaks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.alumni_profiles(id) ON DELETE CASCADE,
  auth_user_id UUID NULL,
  current_streak INTEGER NOT NULL DEFAULT 0 CHECK (current_streak >= 0),
  max_streak INTEGER NOT NULL DEFAULT 0 CHECK (max_streak >= 0),
  last_answered_date DATE NULL,
  history JSONB NOT NULL DEFAULT '[]'::jsonb,
  milestone_badges TEXT[] NOT NULL DEFAULT '{}'::text[],
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_user_streaks_user_id UNIQUE (user_id)
);

-- Index for quick user streak lookup
CREATE INDEX IF NOT EXISTS idx_user_streaks_user_id ON public.user_streaks(user_id);
CREATE INDEX IF NOT EXISTS idx_user_streaks_auth_user_id ON public.user_streaks(auth_user_id) WHERE auth_user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_user_streaks_last_answered_date ON public.user_streaks(last_answered_date);

-- 2. daily_question_answers table (Powers the Reveal Gate)
CREATE TABLE IF NOT EXISTS public.daily_question_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.alumni_profiles(id) ON DELETE CASCADE,
  question_date DATE NOT NULL,
  question_index INTEGER NOT NULL DEFAULT 1,
  question_text TEXT NOT NULL,
  answer_text TEXT NOT NULL,
  post_id BIGINT NULL REFERENCES public.posts(id) ON DELETE SET NULL,
  likes_count INTEGER NOT NULL DEFAULT 0 CHECK (likes_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_daily_answer_user_date UNIQUE (user_id, question_date)
);

-- Indexes for question date queries
CREATE INDEX IF NOT EXISTS idx_daily_answers_date ON public.daily_question_answers(question_date DESC);
CREATE INDEX IF NOT EXISTS idx_daily_answers_user ON public.daily_question_answers(user_id);

