EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- 2. Featured Alumni Table
CREATE TABLE IF NOT EXISTS public.featured_alumni (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  full_name TEXT NOT NULL,
  avatar_url TEXT NOT NULL DEFAULT 'https://images.unsplash.com/photo-1534528741775-53994a69daeb?w=400&auto=format&fit=crop&q=80',
  cover_url TEXT DEFAULT '',
  batch_year INT NOT NULL CHECK (batch_year >= 1 AND batch_year <= 2100),
  session TEXT,
  academic_group TEXT DEFAULT 'Science',
  college_roll TEXT,
  profession TEXT NOT NULL,
  position TEXT NOT NULL,
  institution TEXT NOT NULL,
  city TEXT DEFAULT 'Dhaka',
  country TEXT DEFAULT 'Bangladesh',
  category TEXT DEFAULT 'all' CHECK (category IN ('all', 'tech', 'medicine', 'governance', 'academia', 'global')),
  specialties TEXT[] DEFAULT '{}',
  degrees TEXT[] DEFAULT '{}',
  badges TEXT[] DEFAULT '{}',
  bio TEXT,
  career_history TEXT[] DEFAULT '{}',
  display_order INT DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.featured_alumni ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can view active featured alumni" ON public.featured_alumni;
CREATE POLICY "Public can view active featured alumni"
  ON public.featured_alumni FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Admins can manage featured alumni" ON public.featured_alumni;
CREATE POLICY "Admins can manage featured alumni"
  ON public.featured_alumni FOR ALL
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.alumni_profiles p
      WHERE p.auth_user_id = auth.uid()
        AND p.role IN ('admin', 'moderator')
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.alumni_profiles p
      WHERE p.auth_user_id = auth.uid()
        AND p.role IN ('admin', 'moderator')
    )
  );

-- 3. Career Opportunities & Applications Tables
CREATE TABLE IF NOT EXISTS public.career_opportunities (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  company TEXT NOT NULL,
  location TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('job', 'internship', 'referral')),
  description TEXT NOT NULL,
  poster_id BIGINT NOT NULL,
  poster_name TEXT NOT NULL,
  poster_batch TEXT NOT NULL,
  poster_avatar TEXT,
  poster_email TEXT,
  poster_auth_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'closed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.career_opportunities ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can view career opportunities" ON public.career_opportunities;
CREATE POLICY "Public can view career opportunities"
  ON public.career_opportunities FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Authenticated can insert career opportunities" ON public.career_opportunities;
CREATE POLICY "Authenticated can insert career opportunities"
  ON public.career_opportunities FOR INSERT
  TO authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Posters and Admins can update career opportunities" ON public.career_opportunities;
CREATE POLICY "Posters and Admins can update career opportunities"
  ON public.career_opportunities FOR UPDATE
  TO authenticated
  USING (
    poster_auth_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM public.alumni_profiles p
      WHERE p.auth_user_id = auth.uid() AND p.role IN ('admin', 'moderator')
    )
  );

CREATE TABLE IF NOT EXISTS public.career_applications (
  id TEXT PRIMARY KEY,
  opportunity_id TEXT NOT NULL REFERENCES public.career_opportunities(id) ON DELETE CASCADE,
  applicant_id BIGINT NOT NULL,
  applicant_name TEXT NOT NULL,
  applicant_batch TEXT,
  applicant_avatar TEXT,
  applicant_email TEXT,
  applicant_phone TEXT,
  applicant_auth_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'submitted',
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.career_applications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Applicants and Posters can view applications" ON public.career_applications;
CREATE POLICY "Applicants and Posters can view applications"
  ON public.career_applications FOR SELECT
  TO authenticated
  USING (
    applicant_auth_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM public.career_opportunities o
      WHERE o.id = career_applications.opportunity_id
        AND (o.poster_auth_id = auth.uid() OR EXISTS (
          SELECT 1 FROM public.alumni_profiles p
          WHERE p.auth_user_id = auth.uid() AND p.role IN ('admin', 'moderator')
        ))
    )
  );

DROP POLICY IF EXISTS "Authenticated can apply to career opportunities" ON public.career_applications;
CREATE POLICY "Authenticated can apply to career opportunities"
  ON public.career_applications FOR INSERT
  TO authenticated
  WITH CHECK (true);

-- 4. Mentorship Tables
CREATE TABLE IF NOT EXISTS public.mentor_profiles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name TEXT NOT NULL,
  batch_year INTEGER,
  avatar_url TEXT,
  category TEXT NOT NULL CHECK (category IN ('Medical', 'Job', 'Abroad', 'Degree', 'Business', 'Other')),
  expertise TEXT NOT NULL,
  short_description TEXT NOT NULL,
  institution TEXT,
  position TEXT,
  contact_preference TEXT DEFAULT 'Email / Message',
  is_active BOOLEAN DEFAULT TRUE NOT NULL,
  is_verified BOOLEAN DEFAULT TRUE NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.mentor_profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can view active mentor profiles" ON public.mentor_profiles;
CREATE POLICY "Public can view active mentor profiles"
  ON public.mentor_profiles FOR SELECT
  USING (is_active = TRUE);

DROP POLICY IF EXISTS "Authenticated can manage own mentor profile" ON public.mentor_profiles;
CREATE POLICY "Authenticated can manage own mentor profile"
  ON public.mentor_profiles FOR ALL
  TO authenticated
  USING (user_id = auth.uid())
  WITH CHECK (user_id = auth.uid());

CREATE TABLE IF NOT EXISTS public.mentorship_requests (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  user_name TEXT NOT NULL,
  user_batch INTEGER,
  user_avatar TEXT,
  topic TEXT NOT NULL CHECK (topic IN ('Medical', 'Job', 'Abroad', 'Degree', 'Business', 'Other')),
  question TEXT NOT NULL,
  contact_info TEXT,
  status TEXT DEFAULT 'open' NOT NULL CHECK (status IN ('open', 'answered', 'closed', 'resolved')),
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.mentorship_requests ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can view mentorship requests" ON public.mentorship_requests;
CREATE POLICY "Public can view mentorship requests"
  ON public.mentorship_requests FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Authenticated can submit mentorship requests" ON public.mentorship_requests;
CREATE POLICY "Authenticated can submit mentorship requests"
  ON public.mentorship_requests FOR INSERT
  TO authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Owners and Admins can update mentorship requests" ON public.mentorship_requests;
CREATE POLICY "Owners and Admins can update mentorship requests"
  ON public.mentorship_requests FOR UPDATE
  TO authenticated
  USING (
    user_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM public.alumni_profiles p
      WHERE p.auth_user_id = auth.uid() AND p.role IN ('admin', 'moderator')
    )
  );

CREATE TABLE IF NOT EXISTS public.mentorship_answers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id UUID NOT NULL REFERENCES public.mentorship_requests(id) ON DELETE CASCADE,
  mentor_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  mentor_profile_id BIGINT REFERENCES public.alumni_profiles(id) ON DELETE SET NULL,
  mentor_name TEXT NOT NULL,
  mentor_batch INTEGER,
  mentor_avatar TEXT,
  mentor_profession TEXT,
  answer_text TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
