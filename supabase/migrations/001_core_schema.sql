  academic_group VARCHAR(32) NULL,
  doc_type public.verification_doc_type NOT NULL,
  doc_type_label VARCHAR(128) NOT NULL,
  storage_object_path TEXT NOT NULL CHECK (char_length(trim(storage_object_path)) > 0),
  status public.request_review_status NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected')),
  reviewed_by BIGINT NULL REFERENCES public.alumni_profiles(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ NULL,
  admin_note TEXT NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_admin_doc_no_self_review CHECK (reviewed_by IS NULL OR reviewed_by <> user_id),
  CONSTRAINT fk_admin_doc_stream_group
    FOREIGN KEY (academic_stream, academic_group)
