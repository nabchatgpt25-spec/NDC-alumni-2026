-- 3.7 admin_doc_submissions
-- Created prior to verification_requests so verification_requests can reference it cleanly.
-- storage_object_path stores the internal path inside the PRIVATE bucket `verification-documents`.
CREATE TABLE IF NOT EXISTS public.admin_doc_submissions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id BIGINT NOT NULL REFERENCES public.alumni_profiles(id) ON DELETE CASCADE,
  batch_year SMALLINT NOT NULL REFERENCES public.batches(batch_year),
  college_roll VARCHAR(32) NOT NULL,
