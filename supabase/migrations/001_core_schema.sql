-- 3.0 academic_stream_groups (Reference / Configuration Table)
-- Validates (academic_stream, academic_group) pairs across alumni and verification
-- tables. Allows group_code IS NULL for stream-level capacity metadata (e.g.,
-- Science expected_group_count = 17 before official Science group codes are added).
CREATE TABLE IF NOT EXISTS public.academic_stream_groups (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stream public.academic_stream_type NOT NULL,
  group_code VARCHAR(32) NULL CHECK (group_code IS NULL OR char_length(trim(group_code)) BETWEEN 1 AND 32),
  expected_group_count SMALLINT NOT NULL CHECK (expected_group_count BETWEEN 1 AND 50),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_academic_stream_group_pair UNIQUE (stream, group_code)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_academic_stream_null_group_metadata
  ON public.academic_stream_groups (stream)
  WHERE group_code IS NULL;

-- 3.1 batches
-- Unverified institutional metadata fields (session, hsc_year, special_note,
-- representative_name, estimated_total) are nullable so Migration 004 never has
-- to seed fabricated institutional facts.
CREATE TABLE IF NOT EXISTS public.batches (
  batch_year SMALLINT PRIMARY KEY CHECK (batch_year BETWEEN 1 AND 150),
  session VARCHAR(64) NULL UNIQUE,
  hsc_year SMALLINT NULL CHECK (hsc_year IS NULL OR (hsc_year BETWEEN 1949 AND 2100)),
  special_note TEXT NULL,
  representative_name TEXT NULL,
  representative_profile_id BIGINT NULL, -- FK added after alumni_profiles is created
  registered_count INTEGER NOT NULL DEFAULT 0 CHECK (registered_count >= 0),
  estimated_total INTEGER NULL CHECK (estimated_total IS NULL OR estimated_total >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 3.2 alumni_profiles
-- Note: Passwords are NEVER stored here. Authentication is handled by auth.users.
-- Sensitive contact fields (email, phone, whatsapp, fb_link, college_roll) are
-- protected by column-level privilege revocations, RLS, and controlled RPCs in 002 & 003.
CREATE TABLE IF NOT EXISTS public.alumni_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000 INCREMENT BY 1) PRIMARY KEY,
  auth_user_id UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  role public.user_role NOT NULL DEFAULT 'member',
  full_name TEXT NOT NULL CHECK (char_length(trim(full_name)) BETWEEN 2 AND 150),
  avatar_url TEXT NOT NULL DEFAULT '/ndc-logo.png',
  cover_url TEXT NULL,
  batch_year SMALLINT NOT NULL REFERENCES public.batches(batch_year) ON UPDATE CASCADE,
  session TEXT NULL,
  academic_stream public.academic_stream_type NULL,
  academic_group VARCHAR(32) NULL,
  section VARCHAR(32) NULL,

  -- Server-controlled verification state
  verification_status public.verification_status NOT NULL DEFAULT 'unverified',
  verification_method public.verification_method NULL,
  vouches_count SMALLINT NOT NULL DEFAULT 0 CHECK (vouches_count >= 0),
  vouch_target_count SMALLINT NOT NULL DEFAULT 2 CHECK (vouch_target_count >= 1),
  verified_at TIMESTAMPTZ NULL,
  verified_by_profile_id BIGINT NULL REFERENCES public.alumni_profiles(id) ON DELETE SET NULL,

  -- Professional & academic directory attributes
  profession TEXT NOT NULL DEFAULT 'Not Specified',
  position TEXT NOT NULL DEFAULT '',
  institution TEXT NOT NULL DEFAULT '',
  cadre TEXT NULL,
  specialty TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
  specialty_other TEXT NULL,
  degree TEXT[] NOT NULL DEFAULT '{"HSC"}'::TEXT[],

  -- Location & map directory coordinates
  city TEXT NOT NULL DEFAULT 'Dhaka',
  country TEXT NOT NULL DEFAULT 'Bangladesh',
  latitude DOUBLE PRECISION NULL CHECK (latitude IS NULL OR (latitude BETWEEN -90.0 AND 90.0)),
  longitude DOUBLE PRECISION NULL CHECK (longitude IS NULL OR (longitude BETWEEN -180.0 AND 180.0)),

  -- Profile narrative & badges
  bio TEXT NULL CHECK (bio IS NULL OR char_length(bio) <= 2500),
  career_history TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
  badges TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
  blood_group public.blood_group_type NULL,

  -- Sensitive / Private fields (column-level SELECT revoked from PUBLIC/anon/authenticated in 003)
  college_roll VARCHAR(32) NULL,
  email extensions.citext NULL UNIQUE,
  phone VARCHAR(32) NULL UNIQUE,
  whatsapp VARCHAR(32) NULL,
  fb_link TEXT NULL,

  -- Privacy & activity metadata
  is_public BOOLEAN NOT NULL DEFAULT TRUE,
  show_contact_to_verified BOOLEAN NOT NULL DEFAULT TRUE,
  posts_count INTEGER NOT NULL DEFAULT 0 CHECK (posts_count >= 0),
  last_seen_at TIMESTAMPTZ NULL DEFAULT now(),

  -- Full-Text Search generated column for 100,000+ scale directory search
  -- Excludes sensitive fields (email, phone, whatsapp, college_roll)
  search_vector TSVECTOR GENERATED ALWAYS AS (
    setweight(to_tsvector('simple', coalesce(full_name, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(institution, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(profession, '') || ' ' || coalesce(position, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(city, '') || ' ' || coalesce(country, '')), 'C')
  ) STORED,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_alumni_group_requires_stream
    CHECK (academic_group IS NULL OR academic_stream IS NOT NULL),
  CONSTRAINT fk_alumni_stream_group
    FOREIGN KEY (academic_stream, academic_group)
    REFERENCES public.academic_stream_groups (stream, group_code)
    MATCH SIMPLE
    ON UPDATE CASCADE
);

