  ALTER TABLE public.featured_alumni DROP CONSTRAINT IF EXISTS featured_alumni_batch_year_check;
  ALTER TABLE public.featured_alumni ADD CONSTRAINT featured_alumni_batch_year_check CHECK (batch_year >= 1 AND batch_year <= 2100);
EXCEPTION WHEN others THEN NULL; END $$;

