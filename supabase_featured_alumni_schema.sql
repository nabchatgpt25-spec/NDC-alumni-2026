-- 1. Create the `featured_alumni` Table
CREATE TABLE IF NOT EXISTS public.featured_alumni (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    full_name TEXT NOT NULL,
    avatar_url TEXT NOT NULL DEFAULT 'https://images.unsplash.com/photo-1534528741775-53994a69daeb?w=400&auto=format&fit=crop&q=80',
    cover_url TEXT DEFAULT '',
    batch_year INT NOT NULL CHECK (batch_year >= 1 AND batch_year <= 100),
    session TEXT,
    academic_group TEXT DEFAULT 'Science',
    college_roll TEXT,
    profession TEXT NOT NULL,
    position TEXT NOT NULL,
    institution TEXT NOT NULL,
    city TEXT DEFAULT 'Dhaka',
    country TEXT DEFAULT 'Bangladesh',
    category TEXT DEFAULT 'all' CHECK (category IN ('all', 'tech', 'medicine', 'governance', 'academia', 'global')),
    specialties TEXT[] DEFAULT '{}',
    degrees TEXT[] DEFAULT '{}',
    badges TEXT[] DEFAULT '{}',
    bio TEXT,
    career_history TEXT[] DEFAULT '{}',
    display_order INT DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Indexes for High-Speed Filtering & Sorting
CREATE INDEX IF NOT EXISTS idx_featured_alumni_category ON public.featured_alumni(category);
CREATE INDEX IF NOT EXISTS idx_featured_alumni_active_order ON public.featured_alumni(is_active, display_order ASC, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_featured_alumni_batch ON public.featured_alumni(batch_year);

-- 3. Automatic updated_at Trigger
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_featured_alumni_updated_at ON public.featured_alumni;
CREATE TRIGGER trigger_featured_alumni_updated_at
    BEFORE UPDATE ON public.featured_alumni
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.featured_alumni ENABLE ROW LEVEL SECURITY;

-- 5. RLS Policies
-- A. Anyone (Public & Authenticated) can read active featured luminaries:
DROP POLICY IF EXISTS "Public can view active featured alumni" ON public.featured_alumni;
CREATE POLICY "Public can view active featured alumni"
    ON public.featured_alumni
    FOR SELECT
    USING (is_active = true OR (auth.jwt() ->> 'role') = 'service_role');

-- B. Only Admins can Insert new featured alumni:
DROP POLICY IF EXISTS "Admins can insert featured alumni" ON public.featured_alumni;
CREATE POLICY "Admins can insert featured alumni"
    ON public.featured_alumni
    FOR INSERT
    TO authenticated
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.profiles
            WHERE profiles.id = auth.uid()
              AND profiles.role = 'admin'
        )
        OR (auth.jwt() ->> 'role') = 'service_role'
    );

-- C. Only Admins can Update featured alumni:
DROP POLICY IF EXISTS "Admins can update featured alumni" ON public.featured_alumni;
CREATE POLICY "Admins can update featured alumni"
    ON public.featured_alumni
    FOR UPDATE
    TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.profiles
            WHERE profiles.id = auth.uid()
              AND profiles.role = 'admin'
        )
        OR (auth.jwt() ->> 'role') = 'service_role'
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.profiles
            WHERE profiles.id = auth.uid()
              AND profiles.role = 'admin'
        )
        OR (auth.jwt() ->> 'role') = 'service_role'
    );

-- D. Only Admins can Delete featured alumni:
DROP POLICY IF EXISTS "Admins can delete featured alumni" ON public.featured_alumni;
CREATE POLICY "Admins can delete featured alumni"
    ON public.featured_alumni
    FOR DELETE
    TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.profiles
            WHERE profiles.id = auth.uid()
              AND profiles.role = 'admin'
        )
        OR (auth.jwt() ->> 'role') = 'service_role'
    );

