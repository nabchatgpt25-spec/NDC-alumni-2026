/**
 * Load persisted alumni profiles from local storage, merged with SEED_ALUMNI_PROFILES.
 */
export const loadStoredAlumniProfiles = (): AlumniProfile[] => {
  if (typeof window === 'undefined') return [...SEED_ALUMNI_PROFILES];
  try {
    const raw = localStorage.getItem(PROFILES_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        const merged = [...parsed];
        SEED_ALUMNI_PROFILES.forEach((seed) => {
          if (!merged.some((p) => p.id === seed.id)) {
            merged.push(seed);
          }
        });
        return merged;
      }
    }
  } catch (e) {
    console.warn('Failed to load alumni profiles from storage', e);
  }
  return [...SEED_ALUMNI_PROFILES];
};

/**
 * Save registered alumni profiles into persistent storage.
 */
export const saveStoredAlumniProfiles = (profiles: AlumniProfile[]) => {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(PROFILES_STORAGE_KEY, JSON.stringify(profiles));
  } catch (e) {
    console.warn('Failed to save alumni profiles to storage', e);
  }
};

